/**
 * Função utilitária para sortear N situações autênticas brasileiras sem repetição imediata
 */
export function getFreshBrazilianSituations(count: number = 6, excludeIds: string[] = []): PresetSituation[] {
  const available = BRAZILIAN_EVERYDAY_SITUATIONS.filter((s) => !excludeIds.includes(s.id));
  const pool = available.length >= count ? available : BRAZILIAN_EVERYDAY_SITUATIONS;
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

/**
 * Função utilitária para sortear situações de acordo com o tom emocional escolhido
 */
export function getFreshSituationsByTone(count: number = 6, tone?: StoryTone, excludeIds: string[] = []): PresetSituation[] {
  let basePool = BRAZILIAN_EVERYDAY_SITUATIONS;
  if (tone === "emocionante") {
    basePool = EMOTIONAL_STORY_PRESETS;
  } else if (tone === "comedia") {
    basePool = BRAZILIAN_EVERYDAY_SITUATIONS.filter((s) => s.storyTone === "comedia" || !s.storyTone);
  }

  const available = basePool.filter((s) => !excludeIds.includes(s.id));
  const pool = available.length >= count ? available : basePool;
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

